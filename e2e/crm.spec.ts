import { chromium, expect, test } from "@playwright/test";
import { BASE } from "./base";

test("contacts and pipeline: save, link, note, edit, reload, drag and keyboard move", async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ baseURL: BASE });
  await context.addCookies([{ name: "pramaan_member", value: "mbr_owner", url: BASE }]);
  const page = await context.newPage();
  const suffix = Date.now().toString(36);
  const company = `Willow Studio ${suffix}`;
  const person = `Jamie Reed ${suffix}`;
  const title = `Studio project ${suffix}`;
  try {
    await page.goto("/contacts");
    await page.getByRole("button", { name: "Add company" }).click();
    await page.getByLabel("Name", { exact: true }).fill(company);
    await page.getByRole("button", { name: "Save contact" }).click();
    await expect(page.getByRole("status")).toHaveText("Saved.");
    await page.getByRole("button", { name: "Add person" }).click();
    await page.getByLabel("Name", { exact: true }).fill(person);
    await page.getByLabel("Email", { exact: true }).fill("jamie@example.com");
    await page.getByRole("combobox", { name: "Company", exact: true }).selectOption({ label: company });
    await page.getByRole("button", { name: "Save contact" }).click();
    await expect(page.getByRole("status")).toHaveText("Saved.");
    await page.getByLabel("Search people and companies").fill("jamie@example.com");
    await page.getByRole("button", { name: person, exact: true }).click();
    const details = page.getByRole("region", { name: "Contact details" });
    await expect(details).toContainText(`Company: ${company}`);
    await page.getByLabel("New note").fill("Call after the studio visit.");
    await page.getByRole("button", { name: "Add note" }).click();
    await expect(page.getByRole("list", { name: "Notes", exact: true })).toContainText("Call after the studio visit.");
    await page.getByRole("button", { name: "Edit contact", exact: true }).click();
    await page.getByLabel("Name", { exact: true }).fill(`${person} Updated`);
    await page.getByRole("button", { name: "Save contact" }).click();
    await expect(details).toContainText(`${person} Updated`);
    await expect(page.getByRole("list", { name: "History", exact: true })).toContainText("Contact updated");
    await page.reload();
    await page.getByRole("button", { name: `${person} Updated`, exact: true }).click();
    await expect(page.getByRole("list", { name: "Notes", exact: true })).toContainText("Call after the studio visit.");
    await page.screenshot({ path: "test-results/crm-contacts.png", fullPage: true });
    await page.getByRole("link", { name: "Pipeline", exact: true }).click();
    await page.getByRole("button", { name: "Add card", exact: true }).click();
    await page.getByLabel("Title", { exact: true }).fill(title);
    await page.getByLabel("Value (£)", { exact: true }).fill("1250.29");
    await page.getByLabel("Owner", { exact: true }).fill("Jamie");
    await page.getByRole("button", { name: "Save card" }).click();
    const card = page.getByRole("article", { name: title, exact: true });
    await expect(card).toContainText("£1,250.29");
    await expect(page.getByRole("region", { name: "New", exact: true }).locator(":scope > p")).toContainText("£1,250.29");
    await card.getByRole("button", { name: `Move ${title}`, exact: true }).focus();
    await page.keyboard.press("ArrowRight");
    await expect(page.getByRole("region", { name: "In progress", exact: true })).toContainText(title);
    await expect(card.getByRole("button", { name: `Move ${title}`, exact: true })).toBeFocused();
    await page.keyboard.press("ArrowRight");
    await expect(page.getByRole("region", { name: "Won", exact: true })).toContainText(title);
    await expect(page.getByRole("region", { name: "Won", exact: true }).locator(":scope > p")).toContainText("£1,250.29");
    await card.dragTo(page.getByRole("region", { name: "New", exact: true }));
    await expect(page.getByRole("region", { name: "New", exact: true })).toContainText(title);
    await card.getByRole("button", { name: `Edit ${title}`, exact: true }).click();
    await page.getByRole("combobox", { name: "Type", exact: true }).selectOption("task");
    await page.getByLabel("Owner", { exact: true }).fill("Morgan");
    await page.getByLabel("Value (£)", { exact: true }).fill("99.50");
    await page.getByRole("button", { name: "Save card" }).click();
    await expect(card).toContainText("Morgan");
    await card.getByRole("combobox", { name: `Stage for ${title}`, exact: true }).selectOption("In progress");
    await expect(page.getByRole("region", { name: "In progress", exact: true })).toContainText(title);
    await page.reload();
    await expect(card).toContainText("Task · £99.50");
    await expect(card).toContainText("Owner: Morgan");
    await expect(page.getByRole("region", { name: "In progress", exact: true }).locator(":scope > p")).toContainText("£99.50");
    await expect(page.locator("body")).not.toContainText(/mbr_|companyId|DATABASE_URL|PRAMAAN_API_KEY/);
    await page.screenshot({ path: "test-results/crm-pipeline.png", fullPage: true });

    // An old form in one tab must not undo a newer move in another.
    await card.getByRole("button", { name: `Edit ${title}`, exact: true }).click();
    await expect(page.getByLabel("Title", { exact: true })).toBeFocused();
    await page.getByLabel("Title", { exact: true }).fill(`${title} draft`);
    await expect(card.getByRole("button", { name: `Move ${title}`, exact: true })).toHaveAttribute("aria-disabled", "true");
    await expect(card.getByRole("combobox", { name: `Stage for ${title}`, exact: true })).toBeDisabled();
    await expect(card.getByRole("button", { name: `Delete ${title}`, exact: true })).toBeDisabled();
    await expect(card).toHaveAttribute("draggable", "false");
    const otherTab = await context.newPage();
    await otherTab.goto("/pipeline");
    await otherTab.getByRole("article", { name: title, exact: true }).getByRole("combobox", { name: `Stage for ${title}`, exact: true }).selectOption("Won");
    await expect(otherTab.getByRole("region", { name: "Won", exact: true })).toContainText(title);
    await otherTab.close();
    await page.getByRole("button", { name: "Save card", exact: true }).click();
    await expect(page.getByRole("status")).toHaveText("This card changed since you opened it. Reload to see the latest.");
    await expect(page.getByLabel("Title", { exact: true })).toHaveValue(`${title} draft`);
    await page.getByRole("button", { name: "Refresh board", exact: true }).click();
    await expect(page.getByRole("region", { name: "Won", exact: true })).toContainText(title);
    await expect(page.getByLabel("Title", { exact: true })).toHaveValue(`${title} draft`);
    await page.getByRole("button", { name: "Replace draft with latest card", exact: true }).click();
    await expect(page.getByLabel("Title", { exact: true })).toHaveValue(title);
    await expect(page.getByLabel("Title", { exact: true })).toBeFocused();
    await page.getByRole("button", { name: "Cancel", exact: true }).click();
    await expect(card.getByRole("button", { name: `Edit ${title}`, exact: true })).toBeFocused();
    const handle = card.getByRole("button", { name: `Move ${title}`, exact: true });
    await handle.focus();
    await page.keyboard.press("ArrowRight");
    await expect(page.getByRole("status")).toHaveText("Already in the last stage.");
    await page.route("**/api/pramaan/pipeline", async route => {
      if (route.request().method() === "POST") await route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: { message: "Please try moving this card again." } }) });
      else await route.continue();
    });
    await card.getByRole("combobox", { name: `Stage for ${title}`, exact: true }).selectOption("New");
    await expect(page.getByRole("status")).toHaveText("Please try moving this card again.");
    await expect(handle).toBeFocused();
    await page.unroute("**/api/pramaan/pipeline");
    await page.getByRole("button", { name: "Add card", exact: true }).click();
    await expect(page.getByLabel("Title", { exact: true })).toBeFocused();
    await page.getByLabel("Title", { exact: true }).fill(`${title} other`);
    await page.getByLabel("Owner", { exact: true }).fill("Jamie");
    await page.getByRole("button", { name: "Save card", exact: true }).click();
    const secondCard = page.getByRole("article", { name: `${title} other`, exact: true });
    await expect(secondCard).toBeVisible();
    await card.getByRole("button", { name: `Edit ${title}`, exact: true }).click();
    await page.getByLabel("Title", { exact: true }).fill("Keep this draft");
    await secondCard.getByRole("combobox", { name: `Stage for ${title} other`, exact: true }).selectOption("In progress");
    await expect(page.getByRole("status")).toHaveText(`${title} other moved to In progress.`);
    await expect(page.getByLabel("Title", { exact: true })).toHaveValue("Keep this draft");
    await page.getByRole("button", { name: "Cancel", exact: true }).click();
    await secondCard.getByRole("button", { name: `Delete ${title} other`, exact: true }).click();
    await page.getByRole("button", { name: "Keep card", exact: true }).click();
    await expect(secondCard).toBeVisible();
    await secondCard.getByRole("button", { name: `Delete ${title} other`, exact: true }).click();
    await page.getByRole("alertdialog", { name: "Delete card?", exact: true }).getByRole("button", { name: "Confirm delete", exact: true }).click();
    await expect(secondCard).toHaveCount(0);

    await page.getByRole("link", { name: "Contacts", exact: true }).click();
    await page.getByRole("button", { name: `${person} Updated`, exact: true }).click();
    await page.getByRole("button", { name: "Edit contact", exact: true }).click();
    await expect(page.getByLabel("Name", { exact: true })).toBeFocused();
    await page.getByLabel("Name", { exact: true }).fill("Keep this contact draft");
    await expect(page.getByLabel("New note", { exact: true })).toBeDisabled();
    await expect(page.getByRole("button", { name: "Add note", exact: true })).toBeDisabled();
    await expect(page.getByRole("button", { name: "Delete note 1", exact: true })).toBeDisabled();
    await expect(page.getByRole("button", { name: "Delete contact", exact: true })).toBeDisabled();
    const contactTab = await context.newPage();
    await contactTab.goto("/contacts");
    await contactTab.getByRole("button", { name: `${person} Updated`, exact: true }).click();
    await contactTab.getByLabel("New note", { exact: true }).fill("Note from another tab.");
    await contactTab.getByRole("button", { name: "Add note", exact: true }).click();
    await expect(contactTab.getByRole("list", { name: "Notes", exact: true })).toContainText("Note from another tab.");
    await contactTab.close();
    await expect(page.getByLabel("Name", { exact: true })).toHaveValue("Keep this contact draft");
    await page.getByRole("button", { name: "Save contact", exact: true }).click();
    await expect(page.getByRole("status")).toHaveText("This contact changed since you opened it. Reload to see the latest.");
    await page.getByRole("button", { name: "Replace draft with latest contact", exact: true }).click();
    await expect(page.getByLabel("Name", { exact: true })).toHaveValue(`${person} Updated`);
    await page.getByRole("button", { name: "Cancel", exact: true }).click();
    await expect(page.getByRole("button", { name: "Edit contact", exact: true })).toBeFocused();
    await page.getByRole("button", { name: "Delete note 1", exact: true }).click();
    await page.getByRole("alertdialog", { name: "Delete note?", exact: true }).getByRole("button", { name: "Confirm delete", exact: true }).click();
    await expect(page.getByRole("list", { name: "Notes", exact: true })).not.toContainText("Note from another tab.");
    await page.getByRole("button", { name: company, exact: true }).click();
    await page.getByRole("button", { name: "Delete contact", exact: true }).click();
    await page.getByRole("alertdialog", { name: "Delete contact?", exact: true }).getByRole("button", { name: "Confirm delete", exact: true }).click();
    await expect(page.getByRole("button", { name: company, exact: true })).toHaveCount(0);
    await page.getByRole("button", { name: `${person} Updated`, exact: true }).click();
    await expect(page.getByRole("list", { name: "History", exact: true })).toContainText("Company link removed");
    await expect(page.getByRole("region", { name: "Contact details", exact: true })).not.toContainText(`Company: ${company}`);

  } finally { await browser.close(); }
});
