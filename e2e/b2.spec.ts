const as = (page: Page, member: string) => page.context().addCookies([{ name: "pramaan_member", value: member, domain: "localhost", path: "/" }]);
const shoot = async (page: Page, name: string) => {
  for (const mode of ["light", "dark"]) {
    await page.setViewportSize({ width: 1142, height: 732 });
    await page.evaluate(mode => document.documentElement.classList.toggle("dark", mode === "dark"), mode);
    await page.screenshot({ path: `.scratch/b2/${name}-${mode}.png` });
  }
  await page.evaluate(() => document.documentElement.classList.remove("dark"));
};
async function post(page: Page, title: string, extra: { category?: string; pay?: string; price?: string; location?: string } = {}) {
  await page.goto("/listings/mine");
  await page.getByRole("button", { name: "Post a listing" }).click();
  await page.getByRole("textbox", { name: "Title" }).fill(title);
  await page.getByRole("textbox", { name: "Description" }).fill(`All about ${title}`);
  await page.getByRole("combobox", { name: "Category" }).selectOption(extra.category ?? "Services");
  await page.getByLabel("Price or pay, as you want it shown").fill(extra.pay ?? "$25 an hour");
  await page.getByLabel("Price as a number, for price filters").fill(extra.price ?? "25");
  await page.getByRole("textbox", { name: "Location" }).fill(extra.location ?? "Pune");
  await page.getByRole("button", { name: "Save listing" }).click();
  await expect(page.getByRole("status")).toHaveText("Listing posted. You can add photos below.");
  await expect(page.getByRole("link", { name: title, exact: true })).toBeVisible();
}
const openListing = async (page: Page, title: string) => {
  await page.goto("/listings");
  await page.getByRole("search").locator("input[name=q]").fill(title);
  await page.getByRole("button", { name: "Search listings" }).click();
  await page.getByRole("link", { name: title, exact: true }).click();
  await expect(page.getByRole("article", { name: "Listing" })).toContainText(title);
};
const stamp = () => `run${Date.now().toString(36)}`;

test("listings: post with a photo, search, filter, edit and close", async ({ page }) => {
  const word = stamp(), title = `Garden help ${word}`;
  await as(page, "mbr_poster");
  await post(page, title, { price: "30", location: `Pune ${word}` });
  await page.getByLabel(`Add a photo to ${title}`).setInputFiles({ name: "garden.png", mimeType: "image/png", buffer: png });
  await expect(page.getByRole("status")).toHaveText("Photo added.");
  await shoot(page, "my-listings");
  await as(page, "none");
  await page.goto("/listings");
  const search = page.getByRole("search");
  await search.locator("input[name=q]").fill(word);
  await search.getByLabel("Location").fill(`pune ${word}`);
  await search.getByLabel("Lowest price").fill("20");
  await search.getByLabel("Highest price").fill("40");
  await page.getByRole("button", { name: "Search listings" }).click();
  const results = page.getByRole("region", { name: "Listings" });
  await expect(results.getByRole("status")).toHaveText("1 listing");
  await expect(results.getByRole("listitem").locator("img")).toBeVisible();
  await shoot(page, "listings");
  await search.getByLabel("Highest price").fill("25");
  await page.getByRole("button", { name: "Search listings" }).click();
  await expect(results.getByRole("status")).toHaveText("No listings match. Try fewer filters.");
  await search.getByLabel("Highest price").fill("");
  await page.getByRole("button", { name: "Search listings" }).click();
  await results.getByRole("link", { name: title }).click();
  const article = page.getByRole("article", { name: "Listing" });
  await expect(article).toContainText("$25 an hour");
  await expect(page.getByRole("img", { name: `Photo 1 of ${title}` })).toBeVisible();
  await expect(page.getByRole("region", { name: /Safety/ })).toHaveCount(0);
  await shoot(page, "listing");
  expect((await page.request.post("/api/pramaan/listings", { data: { action: "save", title: "x", description: "y", category: "Jobs" } })).status()).toBe(401);
  await as(page, "mbr_poster");
  await page.goto("/listings/mine");
  await page.getByRole("button", { name: `Edit ${title}` }).click();
  await page.getByRole("textbox", { name: "Title" }).fill(`${title} updated`);
  await page.getByRole("button", { name: "Save listing" }).click();
  await expect(page.getByRole("status")).toHaveText("Listing saved.");
  await page.getByRole("button", { name: `Close ${title} updated` }).click();
  await page.getByRole("button", { name: "Close listing" }).click();
  await expect(page.getByRole("status")).toHaveText("Listing closed.");
  await page.goto("/listings");
  await page.getByRole("search").locator("input[name=q]").fill(word);
  await page.getByRole("button", { name: "Search listings" }).click();
  await expect(page.getByRole("region", { name: "Listings" }).getByRole("status")).toHaveText("No listings match. Try fewer filters.");
  await expect(page.locator("body")).not.toContainText(/mbr_|listing:|\{"|geo\.|\$0\.00/);
});
test("listings: a report, a moderator's hide and a block take it out of sight", async ({ page }) => {
  const word = stamp(), hidden = `Bad item ${word}`, kept = `Good item ${word}`;
  await as(page, "mbr_poster");
  await post(page, hidden);
  await post(page, kept);
  await as(page, "mbr_viewer");
  await openListing(page, hidden);
  const url = page.url();
  const item = page.getByRole("region", { name: "Safety for This listing" });
  await item.getByLabel("Reason").fill(`Spam ${word}`);
  await item.getByRole("button", { name: "Report item" }).click();
  await expect(item.getByRole("status")).toHaveText("Report sent.");
  await as(page, "mbr_owner");
  await page.goto("/moderation");
  const report = page.getByRole("region", { name: "Moderator queue" }).getByRole("listitem").filter({ hasText: `Spam ${word}` });
  await expect(report).toContainText(`Listing: ${hidden}`);
  await report.getByRole("button", { name: "Hide item" }).click();
  await expect(report).toContainText("Hidden");
  await as(page, "mbr_viewer");
  await page.goto(url);
  await expect(page.locator("main").getByRole("alert")).toContainText("This listing isn't available.");
  await page.goto("/listings");
  await page.getByRole("search").locator("input[name=q]").fill(word);
  await page.getByRole("button", { name: "Search listings" }).click();
  const results = page.getByRole("region", { name: "Listings" });
  await expect(results.getByRole("status")).toHaveText("1 listing");
  await expect(results).not.toContainText(hidden);
  await as(page, "mbr_poster");
  await page.goto("/listings/mine");
  await expect(page.getByRole("listitem").filter({ hasText: hidden })).toContainText("Hidden");
  await as(page, "mbr_viewer");
  await openListing(page, kept);
  const person = page.getByRole("region", { name: "Safety for The person who posted this" });
  await person.getByRole("button", { name: "Block person", exact: true }).click();
  await expect(person.getByRole("status")).toHaveText("Person blocked.");
  await page.reload();
  await expect(page.locator("main").getByRole("alert")).toContainText("This listing isn't available.");
  await page.goto("/listings");
  await page.getByRole("search").locator("input[name=q]").fill(word);
  await page.getByRole("button", { name: "Search listings" }).click();
  await expect(page.getByRole("region", { name: "Listings" }).getByRole("status")).toHaveText("No listings match. Try fewer filters.");
  const unblock = await page.request.post("/api/pramaan/moderation", { data: { action: "unblock", ref: "mbr_poster" } });
  expect(unblock.ok()).toBeTruthy();
});
test("applications: a failed file upload keeps the application, and the file can follow", async ({ page }) => {
  const title = `Weekend cover ${stamp()}`;
  await as(page, "mbr_poster");
  await post(page, title);
  await as(page, "mbr_kim");
  await openListing(page, title);
  await page.getByRole("link", { name: "Apply" }).click();
  await page.getByRole("textbox", { name: "Your name" }).fill("Kim");
  await page.getByRole("textbox", { name: "Message" }).fill("Happy to help");
  await page.getByLabel("File, optional").setInputFiles({ name: "cv.png", mimeType: "image/png", buffer: png });
  await page.route("**/api/demo/storage/**", route => route.fulfill({ status: 500 }));
  await page.getByRole("button", { name: "Send application" }).click();
  await expect(page.getByRole("region", { name: "Apply" }).getByRole("status")).toHaveText("Application sent, but the file didn't upload. You can add it from your applications.");
  await page.unroute("**/api/demo/storage/**");
  await page.getByRole("link", { name: "See your applications" }).click();
  const mine = page.getByRole("list", { name: "Your applications" }).getByRole("listitem").filter({ hasText: title }).first();
  await mine.getByLabel("Add a file to this application").setInputFiles({ name: "cv.png", mimeType: "image/png", buffer: png });
  await expect(mine.getByRole("link", { name: /Open attached file/ })).toBeVisible();
});
test("applications: apply with a file, move, message, and see it from both sides", async ({ page }) => {
  const word = stamp(), title = `Night shift ${word}`;
  await as(page, "mbr_poster");
  await post(page, title, { category: "Jobs" });
  await as(page, "mbr_sam");
  await openListing(page, title);
  const url = page.url();
  await page.getByRole("link", { name: "Apply" }).click();
  await page.getByRole("textbox", { name: "Your name" }).fill("Sam Rao");
  await page.getByRole("textbox", { name: "Message" }).fill("I have five years of experience");
  await page.getByLabel("File, optional").setInputFiles({ name: "cv.png", mimeType: "image/png", buffer: png });
  await shoot(page, "apply");
  await page.getByRole("button", { name: "Send application" }).click();
  await expect(page.getByRole("region", { name: "Apply" }).getByRole("status")).toHaveText("Application sent.");
  await page.goto(`${url}/apply`);
  await page.getByRole("textbox", { name: "Your name" }).fill("Sam Rao");
  await page.getByRole("textbox", { name: "Message" }).fill("Again");
  await page.getByRole("button", { name: "Send application" }).click();
  await expect(page.getByRole("region", { name: "Apply" }).getByRole("status")).toHaveText("You already applied to this listing.");
  await page.goto("/applications");
  const mine = page.getByRole("list", { name: "Your applications" }).getByRole("listitem").filter({ hasText: title }).first();
  await expect(mine).toContainText("New");
  await expect(mine.getByRole("link", { name: /Open attached file/ })).toBeVisible();
  await as(page, "mbr_stranger");
  await page.goto(`${url}/applicants`);
  await expect(page.locator("main").getByRole("alert")).toContainText("This listing isn't available.");
  await as(page, "mbr_poster");
  await page.goto(url);
  await page.getByRole("link", { name: "See applicants" }).click();
  const card = page.getByRole("listitem", { name: "Sam Rao" });
  await expect(card).toContainText("I have five years of experience");
  await expect(card.getByRole("link", { name: /Open attached file/ })).toBeVisible();
  await page.getByRole("button", { name: "Shortlist: Sam Rao" }).click();
  await expect(page.getByRole("region", { name: "Applicants" }).getByRole("status").first()).toHaveText("Sam Rao: Shortlisted.");
  await expect(card).toContainText("Shortlisted, set by you");
  await card.getByRole("textbox", { name: "Message Sam Rao" }).fill("Can you start Monday?");
  await card.getByRole("button", { name: "Send message" }).click();
  await expect(card).toContainText("Email sent.");
  await page.getByRole("button", { name: "Accept: Sam Rao" }).click();
  await expect(card).toContainText("Accepted, set by you");
  await shoot(page, "applicants");
  await expect(page.locator("body")).not.toContainText(/mbr_|@example|\{"/);
  await as(page, "mbr_sam");
  await page.goto("/applications");
  await expect(mine).toContainText("Accepted");
  await expect(mine).toContainText("Shortlisted, set by the listing owner");
  await expect(mine).toContainText("Can you start Monday?");
  await shoot(page, "applications");
  await expect(page.locator("body")).not.toContainText(/mbr_|@example|\{"/);
});
